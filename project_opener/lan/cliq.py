"""Zoho Cliq bot client (brief section 3.5).  Owner: builder 1 (CORE+HUB).

One office bot under a shared service account; one token in Settings, stored
with DPAPI (``Settings.cliq_token``).  The client:

* ``lookup_user(email)`` -> Cliq user id (linked once per user in Settings);
* ``dm(user_ids, text)``: the bot messages those users; the text carries a
  ``projectopener://`` link;
* ``post_channel(channel, text)`` for watchers that post to a channel;
* an outbox (``data_dir()/cliq-outbox.jsonl``) retried every ``CLIQ_RETRY_S``
  when Cliq is unreachable; the toast never waits for Cliq.

Verified against Zoho's documentation (5 November 2026):

* Token: a Cliq **webhook token**, generated by the service account under
  Bots & Tools > Webhook Tokens.  It does not expire (it works until deleted;
  at most 5 per user) and is passed as the ``zapikey`` query parameter.  The
  documented endpoints that accept it are the channel, bot ``/incoming`` and
  bot ``/message`` endpoints.
  https://www.zoho.com/cliq/help/platform/webhook-tokens.html
* Bot to users: ``POST {base}/bots/{BOT_UNIQUE_NAME}/message`` with JSON
  ``{"text": ..., "userids": "id1,id2"}`` (comma-separated user ids of the bot's
  subscribers; ``broadcast`` is deprecated).  A user must have subscribed to
  the office bot to receive its messages.
* Bot to a channel: ``POST {base}/channelsbyname/{CHANNEL_UNIQUE_NAME}/message``
  with ``{"text": ...}`` and the query parameter ``bot_unique_name`` (the bot
  must be a participant of the channel).
* User by e-mail: ``GET {base}/users/{EMAIL}`` is documented with OAuth
  (scope ``ZohoCliq.Users.READ``), not with the webhook token.  ``lookup_user``
  tries it with the token and returns "" when Cliq refuses; the user then
  pastes their Cliq user id in Settings (``Settings.cliq_user_id``).
  https://www.zoho.com/cliq/help/restapi/v2/
* Data centres: cliq.zoho.com, .eu, .in, .com.au, .jp, .com.cn, .sa, .uk,
  cliq.zohocloud.ca.  Default base ``https://cliq.zoho.in/api/v2``.

Standard library only (``urllib.request``), timeouts of 10 s, no retries inline.
"""
from __future__ import annotations

import json
import logging
import threading
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from urllib.parse import quote, urlencode

from project_opener.core import models as M
from project_opener.core.jsonio import read_jsonl

log = logging.getLogger(__name__)

TIMEOUT_S = 10
OUTBOX_MAX = 500           # oldest queued messages are dropped beyond this
MAX_ATTEMPTS = 50          # ~4 days at one retry every 5 minutes


@dataclass
class CliqResult:
    ok: bool
    status: int = 0
    message: str = ""
    retry: bool = False        # a transient failure (network, 429, 5xx): worth queueing

    def __bool__(self) -> bool:
        return self.ok


@dataclass
class _Sent:
    method: str
    url: str
    body: dict[str, Any] = field(default_factory=dict)


class CliqClient:
    def __init__(self, api_base: str, bot: str, token: str, outbox: Path, *, dry_run: bool = False,
                 timeout: float = TIMEOUT_S):
        self.api_base = (api_base or "").rstrip("/")
        self.bot = bot
        self.token = token
        self.outbox = Path(outbox)
        self.dry_run = dry_run
        self.timeout = timeout
        self.sent: list[_Sent] = []          # dry-run record
        self._lock = threading.Lock()

    @property
    def configured(self) -> bool:
        return bool(self.api_base and self.bot and self.token)

    # ---------------------------------------------------------------- http
    def _url(self, path: str, **query: str) -> str:
        q = {"zapikey": self.token, **{k: v for k, v in query.items() if v}}
        return f"{self.api_base}{path}?{urlencode(q)}"

    def _request(self, method: str, path: str, body: dict[str, Any] | None = None, **query: str) -> tuple[CliqResult, Any]:
        url = self._url(path, **query)
        if self.dry_run:
            self.sent.append(_Sent(method, url, dict(body or {})))
            log.info("cliq dry run: %s %s %s", method, path, json.dumps(body or {}, ensure_ascii=False)[:300])
            return CliqResult(True, 200, "dry run"), {}
        data = json.dumps(body).encode("utf-8") if body is not None else None
        req = urllib.request.Request(url, data=data, method=method,
                                     headers={"Content-Type": "application/json", "Accept": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:  # noqa: S310 - https base from Settings
                raw = resp.read()
                payload: Any = {}
                if raw:
                    try:
                        payload = json.loads(raw.decode("utf-8"))
                    except ValueError:
                        payload = {}
                return CliqResult(True, resp.status, "sent"), payload
        except urllib.error.HTTPError as exc:
            text = ""
            try:
                text = exc.read().decode("utf-8", "replace")[:300]
            except Exception:  # noqa: BLE001
                pass
            transient = exc.code == 429 or exc.code >= 500
            return CliqResult(False, exc.code, f"Cliq answered {exc.code}: {text or exc.reason}", transient), None
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            reason = getattr(exc, "reason", exc)
            return CliqResult(False, 0, f"Cliq not reachable: {reason}", True), None

    # -------------------------------------------------------------- public
    def lookup_user(self, email: str) -> str:
        """The Cliq user id for ``email``; "" when Cliq does not answer it (see the module notes)."""
        if not (self.configured and email.strip()):
            return ""
        res, payload = self._request("GET", f"/users/{quote(email.strip())}", None, fields="all")
        if not res.ok or not isinstance(payload, dict):
            log.info("Cliq user lookup failed: %s", res.message)
            return ""
        data = payload.get("data", payload)
        if isinstance(data, dict):
            for key in ("id", "user_id", "zuid"):
                if data.get(key):
                    return str(data[key])
        return ""

    def dm(self, user_ids: list[str], text: str) -> CliqResult:
        ids = [str(i).strip() for i in user_ids if str(i).strip()]
        if not self.configured:
            return CliqResult(False, 0, "Cliq is not set up")
        if not ids:
            return CliqResult(False, 0, "no Cliq user ids")
        res, _ = self._request("POST", f"/bots/{quote(self.bot)}/message", {"text": text, "userids": ",".join(ids)})
        return res

    def post_channel(self, channel: str, text: str) -> CliqResult:
        if not self.configured:
            return CliqResult(False, 0, "Cliq is not set up")
        name = channel.strip().lstrip("#")
        if not name:
            return CliqResult(False, 0, "no channel")
        res, _ = self._request("POST", f"/channelsbyname/{quote(name)}/message", {"text": text},
                               bot_unique_name=self.bot)
        return res

    def send(self, kind: str, target: list[str] | str, text: str) -> CliqResult:
        """``dm`` or ``channel``; a transient failure is queued for ``flush_outbox``."""
        res = self.dm(list(target) if isinstance(target, list) else [target], text) if kind == "dm" \
            else self.post_channel(str(target if isinstance(target, str) else ",".join(target)), text)
        if not res.ok and res.retry:
            self.queue(kind, target, text)
        return res

    # -------------------------------------------------------------- outbox
    def queue(self, kind: str, target: list[str] | str, text: str) -> None:
        row = {"id": M.new_id(), "kind": kind, "target": target, "text": text, "queued_at": M.now_iso(),
               "attempts": 0}
        with self._lock:
            rows = read_jsonl(self.outbox)
            rows.append(row)
            self._write_outbox(rows[-OUTBOX_MAX:])

    def pending(self) -> int:
        return len(read_jsonl(self.outbox))

    def _write_outbox(self, rows: list[dict[str, Any]]) -> None:
        self.outbox.parent.mkdir(parents=True, exist_ok=True)
        if not rows:
            try:
                self.outbox.unlink()
            except FileNotFoundError:
                pass
            return
        tmp = self.outbox.with_suffix(".tmp")
        with open(tmp, "w", encoding="utf-8", newline="\n") as f:
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        tmp.replace(self.outbox)

    def flush_outbox(self) -> int:
        """Retry queued messages; returns how many went out."""
        if not self.configured:
            return 0
        with self._lock:
            rows = read_jsonl(self.outbox)
            if not rows:
                return 0
            keep: list[dict[str, Any]] = []
            sent = 0
            reachable = True
            for r in rows:
                if not reachable:            # Cliq is down: do not hammer it with the rest
                    keep.append(r)
                    continue
                kind, target, text = str(r.get("kind", "dm")), r.get("target", []), str(r.get("text", ""))
                res = self.dm(list(target) if isinstance(target, list) else [str(target)], text) if kind == "dm" \
                    else self.post_channel(str(target), text)
                if res.ok:
                    sent += 1
                    continue
                if res.retry:
                    r["attempts"] = int(r.get("attempts", 0) or 0) + 1
                    if r["attempts"] < MAX_ATTEMPTS:
                        keep.append(r)
                    if res.status == 0:
                        reachable = False
                else:
                    log.warning("dropping queued Cliq message (%s)", res.message)
            self._write_outbox(keep)
            return sent

